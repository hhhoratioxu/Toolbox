def dump(row, omit=()):
    result = {}
    for col in row.__table__.columns:
        if col.name in omit:
            continue
        v = getattr(row, col.name)
        result[col.name] = v.isoformat() if isinstance(v, datetime) else v
    return result


def log(db, p, action, target=None, **detail):
    db.add(Audit(owner_id=p.owner, actor=p.actor, action=action, target_id=target, detail=detail))


def policy(db, owner):
    row = db.get(Setting, owner)
    return PolicyInput().model_dump() | ((row.value.get('policy', {})) if row else {})


def normalized(s):
    return re.sub(r'\s+', ' ', s).strip().lower()


def content_hash(body):
    return digest(normalized(body))


def tombstoned(db, owner, kind, value):
    return db.scalar(select(Tombstone.id).where(Tombstone.owner_id == owner, Tombstone.kind == kind, Tombstone.value == value)) is not None


def guard_content(db, owner, body):
    if tombstoned(db, owner, 'content', content_hash(body)) or tombstoned(db, owner, 'rejected_content', content_hash(body)):
        raise HTTPException(410, '内容已被彻底遗忘或纠正，禁止自动重新写入')


def add_tombstone(db, owner, kind, value, journal=False):
    key = digest(owner + ':' + kind + ':' + value)
    if not db.get(Tombstone, key):
        db.add(Tombstone(id=key, owner_id=owner, kind=kind, value=value))
    if journal:
        path = settings.data_dir / 'deletion-ledger.jsonl'
        entry = json.dumps({'id': key, 'owner_id': owner, 'kind': kind, 'value': value}) + '\n'
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        try:
            os.write(fd, entry.encode())
            os.fsync(fd)
        finally:
            os.close(fd)


def serial_lock(db, key):
    # Transaction-scoped PostgreSQL locks also serialize independent API/MCP workers.
    n = int(digest(key)[:15], 16)
    db.execute(text('SELECT pg_advisory_xact_lock(:n)'), {'n': n})


def idem_begin(db, p, key, operation, payload):
    if not key or len(key) > 160:
        raise HTTPException(400, '写入必须提供 1–160 字符的 Idempotency-Key')
    identity = digest(p.actor + ':' + operation + ':' + key)
    serial_lock(db, identity)
    fingerprint = digest(json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str))
    previous = db.get(Idempotency, identity)
    if previous and previous.request_hash != fingerprint:
        raise HTTPException(409, '同一幂等键不能用于不同请求内容')
    return identity, fingerprint, previous


def idem_save(db, identity, fingerprint, kind, result_id):
    db.add(Idempotency(id=identity, request_hash=fingerprint, kind=kind, result_id=result_id))


def source_path(source_id):
    # IDs are generated by the server; never accept a user supplied path.
    if not re.fullmatch(r'[a-f0-9-]{36}', source_id):
        raise ValueError('invalid source id')
    return settings.data_dir / 'sources' / (source_id + '.txt')


def mirror_source(s):
    target = source_path(s.id)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as f:
        f.write(s.content)


def source_allowed(db, p, s):
    if p.admin:
        return True
    if s.blocked or not s.content or (s.retention_until and s.retention_until <= now()):
        return False
    linked = db.scalars(select(Memory).where(Memory.source_id == s.id)).all()
    if any(m.status in ('trash', 'incorrect', 'superseded', 'archived', 'rejected') or (m.valid_from and m.valid_from > now()) or (m.valid_until and m.valid_until <= now()) for m in linked):
        return False
    return True


def get_source(db, p, source_id):
    p.require('read')
    s = db.scalar(select(Source).where(Source.id == source_id, scope_filter(Source, p)))
    if not s or not source_allowed(db, p, s):
        raise HTTPException(404, '来源不存在或不可访问')
    return s


def create_source(db, p, data: SourceInput, key: str):
    serial_lock(db, 'write:' + p.owner)
    p.require('propose')
    write_scope(db, p, data)
    identity, fingerprint, previous = idem_begin(db, p, key, 'source', data.model_dump(mode='json'))
    if previous:
        s = db.get(Source, previous.result_id)
        if not s or s.owner_id != p.owner:
            raise HTTPException(410, '原始记录已删除')
        return s, True
    checksum = digest(data.content)
    if tombstoned(db, p.owner, 'source_hash', checksum) or (tombstoned(db, p.owner, 'blocked_source_hash', checksum) and not (p.admin and data.kind == 'correction')):
        raise HTTPException(410, '此来源已删除或纠正，禁止重新导入')
    scope = f'{data.project_id or "global"}:{data.category}:{data.sensitivity}:{data.external_allowed}'
    serial_lock(db, p.owner + scope + checksum)
    existing = db.scalar(select(Source).where(Source.owner_id == p.owner, Source.scope_key == scope, Source.checksum == checksum))
    if existing:
        idem_save(db, identity, fingerprint, 'source', existing.id)
        return existing, True
    if data.kind == 'json':
        try:
            json.loads(data.content)
        except (ValueError, RecursionError):
            raise HTTPException(422, 'JSON 文件格式无效')
    days = policy(db, p.owner)['source_retention_days']
    s = Source(**data.model_dump(exclude={'extract'}), owner_id=p.owner, scope_key=scope, checksum=checksum,
               created_by=p.actor, retention_until=now() + timedelta(days=days) if days else None)
    db.add(s)
    db.flush()
    mirror_source(s)
    if data.extract and policy(db, p.owner)['write_mode'] != 'manual':
        db.add(Job(owner_id=p.owner, source_id=s.id, kind='extract'))
    idem_save(db, identity, fingerprint, 'source', s.id)
    log(db, p, 'source.ingest', s.id)
    return s, False


def current_memory(db, p, memory_id, lock=False, active_only=False):
    p.require('read')
    stmt = select(Memory).where(Memory.id == memory_id, scope_filter(Memory, p))
    m = db.scalar(stmt.with_for_update() if lock else stmt)
    if not m or (active_only and m.status != 'active'):
        raise HTTPException(404, '记忆不存在或不可访问')
    if not p.admin and ((m.valid_from and m.valid_from > now()) or (m.valid_until and m.valid_until <= now())):
        raise HTTPException(404, '记忆不存在或已失效')
    return m


def snapshot(db, m, reason):
    db.flush()
    db.add(Revision(memory_id=m.id, version=m.version, snapshot=dump(m), reason=reason, actor=m.updated_by))
    idx = db.get(SearchIndex, m.id)
    if idx:
        db.delete(idx)
        db.flush()
    from .retrieval import terms
    db.add(SearchIndex(memory_id=m.id, version=m.version, terms=' '.join(terms(m.title + ' ' + m.body))))
    db.add(Job(owner_id=m.owner_id, memory_id=m.id, kind='embed'))


def evidence_check(db, p, data, s):
    if s.owner_id != p.owner or s.project_id != data.project_id or s.category != data.category:
        raise HTTPException(422, '记忆必须继承来源的项目与分类；请拆分来源后重新导入')
    if data.sensitivity < s.sensitivity or (data.external_allowed and not s.external_allowed):
        raise HTTPException(403, '记忆不能降低来源敏感级别或扩大外部可见范围')
    quote = data.quote or (s.content if len(s.content) <= 40000 else '')
    if not quote or quote not in s.content:
        raise HTTPException(422, '必须提供来源中可逐字定位的原文引用')
    return quote, s.content.index(quote)


def create_memory(db, p, data: MemoryInput, key: str, candidate=False):
    serial_lock(db, 'write:' + p.owner)
    p.require('propose')
    write_scope(db, p, data)
    if not p.admin and policy(db, p.owner)['write_mode'] == 'manual':
        raise HTTPException(403, '当前设置为仅手动创建')
    identity, fingerprint, previous = idem_begin(db, p, key, 'memory', data.model_dump(mode='json') | {'candidate': candidate})
    if previous:
        m = db.get(Memory, previous.result_id)
        if not m or m.owner_id != p.owner:
            raise HTTPException(410, '记忆已彻底删除')
        if not p.admin and m.status == 'trash':
            raise HTTPException(410, '记忆已移入回收站')
        return m, True
    guard_content(db, p.owner, data.body)
    serial_lock(db, p.owner + str(data.project_id) + data.category + content_hash(data.body))
    existing = db.scalar(select(Memory).where(Memory.owner_id == p.owner, Memory.project_id == data.project_id,
                                               Memory.category == data.category, Memory.body == data.body,
                                               Memory.sensitivity == data.sensitivity, Memory.external_allowed == data.external_allowed))
    if existing:
        if existing.status in ('trash', 'incorrect', 'superseded', 'rejected'):
            raise HTTPException(409, '相同内容已有失效或删除记录，不能自动恢复')
        idem_save(db, identity, fingerprint, 'memory', existing.id)
        return existing, True
    if data.source_id:
        s = db.scalar(select(Source).where(Source.id == data.source_id, scope_filter(Source, p)).with_for_update())
        if not s:
            raise HTTPException(404, '来源不存在或不可访问')
        if s.blocked or tombstoned(db, p.owner, 'source_hash', s.checksum) or tombstoned(db, p.owner, 'blocked_source_hash', s.checksum):
            raise HTTPException(409, '此来源曾被纠正或停止提炼，不能再次生成记忆')
    else:
        s, _ = create_source(db, p, SourceInput(title=data.title, content=data.body, project_id=data.project_id,
            category=data.category, kind='note', speaker='user' if p.admin else 'unknown', sensitivity=data.sensitivity,
            external_allowed=data.external_allowed), 'memory-source:' + identity)
    quote, start = evidence_check(db, p, data, s)
    values = data.model_dump(exclude={'source_id', 'quote', 'provenance'})
    values['pinned'] = data.pinned if p.admin else False
    values['locked'] = data.locked if p.admin else False
    m = Memory(**values, owner_id=p.owner, source_id=s.id, quote=quote, quote_start=start, quote_end=start + len(quote),
               evidence_source_ids=[s.id], status='active' if p.admin and not candidate else 'candidate',
               provenance='user_entered' if p.admin and not candidate else ('inferred' if data.provenance == 'inferred' or s.speaker != 'user' else 'extracted'),
               created_by=p.actor, updated_by=p.actor)
    db.add(m)
    db.flush()
    # Conservative title collision detection: review required, never overwrite.
    siblings = db.scalars(select(Memory).where(Memory.owner_id == p.owner, Memory.project_id == m.project_id,
                       Memory.category == m.category, Memory.id != m.id, Memory.status.in_(['active', 'candidate']))).all()
    has_conflict = False
    for other in siblings:
        if normalized(other.title) == normalized(m.title) or difflib.SequenceMatcher(None, other.body, m.body).ratio() > .85:
            db.add(Relation(left_id=other.id, right_id=m.id, kind='conflict' if other.body != m.body else 'duplicate'))
            m.status = 'candidate'
            has_conflict = True
    cfg = policy(db, p.owner)
    if (not p.admin and cfg['write_mode'] == 'auto' and m.category in cfg['auto_categories']
        and m.project_id in cfg['auto_projects'] and m.provenance == 'extracted' and s.speaker == 'user'
        and not has_conflict):
        # Automatic retention is not user confirmation; high-risk profile/facts always require review.
        if m.category not in ('profile', 'fact'):
            m.status = 'active'
    snapshot(db, m, '创建')
    idem_save(db, identity, fingerprint, 'memory', m.id)
    log(db, p, 'memory.create', m.id, version=m.version, status=m.status)
    return m, False


def check_version(m, expected):
    if m.version != expected:
        raise HTTPException(409, {'message': '记忆已被其他客户端修改，请重新加载后合并', 'current_version': m.version})


def protect_correction(db, m):
    add_tombstone(db, m.owner_id, 'rejected_content', content_hash(m.body))
    for source_id in m.evidence_source_ids:
        s = db.get(Source, source_id)
        if s:
            s.blocked = True
            add_tombstone(db, m.owner_id, 'blocked_source_hash', s.checksum)


def edit_memory(db, p, memory_id, data, key):
    serial_lock(db, 'write:' + p.owner)
    p.require('update')
    m = current_memory(db, p, memory_id, lock=True)
    identity, fingerprint, previous = idem_begin(db, p, key, 'edit:' + memory_id, data.model_dump(mode='json'))
    if previous:
        return m
    check_version(m, data.expected_version)
    if not p.admin and (m.locked or m.provenance in ('user_entered', 'confirmed')):
        raise HTTPException(403, '用户维护、已确认或锁定的记忆只能由用户本人修改；请提交候选')
    write_scope(db, p, data)
    # Moving a memory would leak its historical source/revisions. Explicit re-import is required.
    if data.project_id != m.project_id or data.category != m.category:
        raise HTTPException(422, '编辑时不可改变项目或分类；请创建有独立来源的新记忆')
    if data.sensitivity < m.sensitivity or (data.external_allowed and not m.external_allowed):
        raise HTTPException(403, '已有记忆不能直接降低可见性保护；请重新导入经过脱敏的来源')
    changed = data.body != m.body or data.title != m.title
    old_summary = m.summary
    if changed:
        if p.admin:
            protect_correction(db, m)
        s, _ = create_source(db, p, SourceInput(title=data.title, content=data.body, project_id=m.project_id, category=m.category,
                    sensitivity=data.sensitivity, external_allowed=data.external_allowed, kind='correction', speaker='user' if p.admin else 'unknown'), 'correction:' + identity)
        m.source_id, m.quote, m.quote_start, m.quote_end = s.id, data.body, 0, len(data.body)
        m.evidence_source_ids = list(dict.fromkeys(m.evidence_source_ids + [s.id]))
    fields = data.model_dump(exclude={'expected_version', 'reason', 'source_id', 'quote', 'provenance'})
    if not p.admin:
        fields.pop('locked', None)
        fields.pop('pinned', None)
    for k, v in fields.items():
        setattr(m, k, v)
    m.summary = data.body[:240] if changed and data.summary == old_summary else (data.summary or data.body[:240])
    m.provenance = 'confirmed' if p.admin else m.provenance
    m.version += 1
    m.updated_at, m.updated_by = now(), p.actor
    snapshot(db, m, data.reason)
    idem_save(db, identity, fingerprint, 'memory', m.id)
    log(db, p, 'memory.edit', m.id, version=m.version)
    return m


def memory_action(db, p, memory_id, data, key):
    serial_lock(db, 'write:' + p.owner)
    admin_only(p)
    m = current_memory(db, p, memory_id, lock=True)
    identity, fingerprint, previous = idem_begin(db, p, key, 'action:' + memory_id, data.model_dump())
    if previous:
        return m
    check_version(m, data.expected_version)
    action = data.action
    if action == 'accept':
        conflict = db.scalar(select(Relation.id).where(or_(Relation.left_id == m.id, Relation.right_id == m.id), Relation.resolved.is_(False)))
        if conflict:
            raise HTTPException(409, '请先在冲突审核中选择有效版本或合并')
        m.status, m.provenance = 'active', 'confirmed'
    elif action == 'restore':
        m.status = 'active' if m.provenance in ('confirmed', 'user_entered') else 'candidate'
    elif action in ('pin', 'unpin', 'lock', 'unlock'):
        setattr(m, 'pinned' if action in ('pin', 'unpin') else 'locked', action in ('pin', 'lock'))
    else:
        m.status = {'reject': 'rejected', 'archive': 'archived', 'trash': 'trash'}[action]
        if action == 'reject':
            protect_correction(db, m)
    m.version += 1
    m.updated_by, m.updated_at = p.actor, now()
    snapshot(db, m, action)
    idem_save(db, identity, fingerprint, 'memory', m.id)
    log(db, p, 'memory.' + action, m.id, version=m.version)
    return m


def memory_detail(db, p, memory_id):
    m = current_memory(db, p, memory_id)
    result = dump(m)
    # Agent only sees evidence for the current effective version; historical originals are owner-only.
    s = db.get(Source, m.source_id)
    source_meta = {k: v for k, v in dump(s).items() if k not in ('content', 'scope_key')} if s else None
    result['source'] = source_meta
    result['revisions'] = []
    if p.admin:
        revisions = db.scalars(select(Revision).where(Revision.memory_id == m.id).order_by(Revision.version.desc())).all()
        for rev in revisions:
            item = dump(rev)
            previous = next((x for x in revisions if x.version == rev.version - 1), None)
            visible_fields = ('title', 'body', 'summary', 'tags', 'status', 'provenance', 'importance', 'sensitivity', 'external_allowed', 'pinned', 'locked', 'valid_from', 'valid_until', 'source_id')
            before = {k: previous.snapshot.get(k) for k in visible_fields} if previous else {}
            after = {k: rev.snapshot.get(k) for k in visible_fields}
            item['diff'] = '\n'.join(difflib.unified_diff(json.dumps(before, ensure_ascii=False, indent=2).splitlines(), json.dumps(after, ensure_ascii=False, indent=2).splitlines(), fromfile='之前', tofile='之后', lineterm=''))
            result['revisions'].append(item)
    else:
        result.pop('evidence_source_ids', None)
    return result
